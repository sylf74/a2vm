def lang_of(value: str | None) -> str:
    return value if value in LABELS else DEFAULT


def t(lang: str, key: str, **kw: object) -> str:
    """The label `key` in `lang` (English when the language is not in the catalogue), formatted."""
    text = LABELS[lang_of(lang)].get(key) or LABELS[DEFAULT][key]
    return text.format(**kw) if kw else text


def has(key: str) -> bool:
    return key in LABELS[DEFAULT]


def check() -> list[str]:
    """Keys missing from a language of the catalogue (a test keeps it empty)."""
    ref = set(LABELS[DEFAULT])
    return [f"{lang}: {k}" for lang, labels in LABELS.items() for k in sorted(ref ^ set(labels))]
